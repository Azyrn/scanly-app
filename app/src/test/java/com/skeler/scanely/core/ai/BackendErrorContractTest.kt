package com.skeler.scanely.core.ai

import com.skeler.scanely.core.network.BackendErrorEnvelope
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.int
import okhttp3.ResponseBody.Companion.toResponseBody
import org.junit.Assert.*
import org.junit.Test
import retrofit2.HttpException
import retrofit2.Response

class BackendErrorContractTest {
    // Every code/status pair from worker/src/errors.ts; details from quota.ts and idempotency.ts.
    private val statuses = mapOf(
        "unauthenticated" to 401, "quota_exceeded" to 402, "rate_limited" to 429,
        "doc_too_large" to 413, "format_not_in_plan" to 402, "unsupported_format" to 415,
        "budget_exhausted" to 503, "provider_error" to 502, "design_failed" to 422,
        "license_invalid" to 404, "license_inactive" to 402, "activation_limit" to 409,
        "claim_invalid" to 404, "claim_used" to 409, "claim_expired" to 410,
        "upgrade_unavailable" to 409, "quote_changed" to 409,
        "bad_request" to 400, "internal" to 500
    )
    private fun failure(status: Int, body: String) =
        HttpException(Response.error<Any>(status, body.toResponseBody())).toAiException()

    @Test fun `all worker error envelopes deserialize and retain retry classification`() {
        // Generated by ApiError.toResponse() from worker/src/errors.ts, with no network calls.
        val fixtures = Json.parseToJsonElement(checkNotNull(javaClass.getResource("/backend/errors.json")).readText()).jsonArray
        assertEquals(statuses.size, fixtures.size)
        for (fixture in fixtures) {
            val body = fixture.jsonObject.getValue("body").toString()
            val status = fixture.jsonObject.getValue("status").jsonPrimitive.int
            val code = fixture.jsonObject.getValue("body").jsonObject.getValue("error")
                .jsonObject.getValue("code").jsonPrimitive.content
            assertEquals(statuses[code], status)
            val dto = Json.decodeFromString<BackendErrorEnvelope>(body).error!!
            assertEquals(code, dto.code)
            val mapped = failure(status, body)
            if (code in setOf("provider_error", "internal", "rate_limited")) {
                assertTrue(code, mapped is TransientAiException)
                assertEquals(30, (mapped as TransientAiException).retryAfterSeconds)
            } else {
                assertEquals(code, (mapped as FatalAiException).result.code)
                assertEquals("pro", mapped.result.requiredTier)
            }
        }
    }

    @Test fun `non JSON authentication and client errors must not retry`() {
        for (status in listOf(400, 401, 403, 404, 413, 415)) {
            assertTrue("status $status", failure(status, "<html>proxy error</html>") is FatalAiException)
        }
    }

    @Test fun `non JSON rate limits and server failures remain transient`() {
        for (status in listOf(429, 500, 502, 503, 504)) {
            assertTrue(failure(status, "") is TransientAiException)
        }
    }
}
