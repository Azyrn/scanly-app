/**
 * Every icon is a large file with a second icon overlapping its lower-right corner, drawn as
 * stacked layers on one 24 grid at stroke 1.5 (generated by scripts/gen_pdf_tool_icons.py).
 * Files wear their format's colour: the back file is the source, a small file in front is the
 * result, and an arrow reads source to result. Actions (pencil, lock, scissors…) are drawn in
 * [IconLayer.format] null, the ink colour. The drawables are not auto-mirrored, so arrows and
 * Rotate keep their direction in right-to-left layouts.
 */
class IconLayer(@DrawableRes val res: Int, val format: ToolFormat?)

private fun layers(vararg parts: Pair<Int, ToolFormat?>) = parts.map { (res, format) -> IconLayer(res, format) }

@get:DrawableRes
private val ToolFormat.backRes: Int
    get() = when (this) {
        ToolFormat.PDF -> R.drawable.ic_tool_back_pdf
        ToolFormat.WORD -> R.drawable.ic_tool_back_word
        ToolFormat.EXCEL -> R.drawable.ic_tool_back_excel
        ToolFormat.POWERPOINT -> R.drawable.ic_tool_back_powerpoint
        ToolFormat.IMAGE -> R.drawable.ic_tool_back_image
    }

@get:DrawableRes
private val ToolFormat.frontRes: Int
    get() = when (this) {
        ToolFormat.PDF -> R.drawable.ic_tool_front_pdf
        ToolFormat.WORD -> R.drawable.ic_tool_front_word
        ToolFormat.EXCEL -> R.drawable.ic_tool_front_excel
        ToolFormat.POWERPOINT -> R.drawable.ic_tool_front_powerpoint
        ToolFormat.IMAGE -> R.drawable.ic_tool_front_image
    }

private fun convert(from: ToolFormat, to: ToolFormat) =
    layers(from.backRes to from, to.frontRes to to, R.drawable.ic_tool_arrow to null)

private fun action(@DrawableRes glyph: Int, on: ToolFormat = ToolFormat.PDF) = layers(on.backRes to on, glyph to null)

val PdfTool.layers: List<IconLayer>
    get() = when (this) {
        PdfTool.MERGE -> layers(
            R.drawable.ic_tool_back_pdf to ToolFormat.PDF,
            R.drawable.ic_tool_front_pdf_plain to ToolFormat.PDF,
            R.drawable.ic_tool_plus to null
        )
        PdfTool.SPLIT -> action(R.drawable.ic_tool_glyph_scissors)
        PdfTool.COMPRESS -> action(R.drawable.ic_tool_glyph_compress)
        PdfTool.PDF_TO_WORD -> convert(ToolFormat.PDF, ToolFormat.WORD)
        PdfTool.PDF_TO_POWERPOINT -> convert(ToolFormat.PDF, ToolFormat.POWERPOINT)
        PdfTool.PDF_TO_EXCEL -> convert(ToolFormat.PDF, ToolFormat.EXCEL)
        PdfTool.WORD_TO_PDF -> convert(ToolFormat.WORD, ToolFormat.PDF)
        PdfTool.POWERPOINT_TO_PDF -> convert(ToolFormat.POWERPOINT, ToolFormat.PDF)
        PdfTool.EXCEL_TO_PDF -> convert(ToolFormat.EXCEL, ToolFormat.PDF)
        PdfTool.EDIT -> action(R.drawable.ic_tool_glyph_pencil)
        PdfTool.PDF_TO_JPG -> convert(ToolFormat.PDF, ToolFormat.IMAGE)
        PdfTool.IMAGE_TO_PDF -> convert(ToolFormat.IMAGE, ToolFormat.PDF)
        PdfTool.PAGE_NUMBERS -> action(R.drawable.ic_tool_glyph_hash)
        PdfTool.WATERMARK -> action(R.drawable.ic_tool_glyph_droplet)
        PdfTool.ROTATE -> action(R.drawable.ic_tool_glyph_rotate)
        PdfTool.UNLOCK -> action(R.drawable.ic_tool_glyph_lock_open)
        PdfTool.PROTECT -> action(R.drawable.ic_tool_glyph_lock)
        PdfTool.ORGANIZE -> action(R.drawable.ic_tool_glyph_sort)
        PdfTool.REPAIR -> action(R.drawable.ic_tool_glyph_wrench)
        PdfTool.SIGN -> action(R.drawable.ic_tool_glyph_signature)
        PdfTool.EXTRACT_TEXT -> action(R.drawable.ic_tool_glyph_letter_t)
        PdfTool.COMPRESS_IMAGE -> action(R.drawable.ic_tool_glyph_compress, on = ToolFormat.IMAGE)
        // A photo stack is "other image formats", a single photo is the JPG.
        PdfTool.CONVERT_TO_JPG -> layers(
            R.drawable.ic_tool_back_image_stack to ToolFormat.IMAGE,
            R.drawable.ic_tool_front_image to ToolFormat.IMAGE,
            R.drawable.ic_tool_arrow to null
        )
        PdfTool.CONVERT_FROM_JPG -> layers(
            R.drawable.ic_tool_back_image to ToolFormat.IMAGE,
            R.drawable.ic_tool_front_image_stack to ToolFormat.IMAGE,
            R.drawable.ic_tool_arrow to null
        )
        PdfTool.RESIZE_IMAGE -> action(R.drawable.ic_tool_glyph_maximize, on = ToolFormat.IMAGE)
    }

/** A file format; each has its own colour on the icons. */
enum class ToolFormat { PDF, WORD, EXCEL, POWERPOINT, IMAGE }

/** Each format has a light and a dark tone; [LocalDarkMode] is the theme the app resolved. */
@Composable
fun ToolFormat.accent(): Color {
    val dark = LocalDarkMode.current
    val res = when (this) {
        ToolFormat.PDF -> if (dark) R.color.pdf_format_pdf_dark else R.color.pdf_format_pdf_light
        ToolFormat.WORD -> if (dark) R.color.pdf_format_word_dark else R.color.pdf_format_word_light
        ToolFormat.EXCEL -> if (dark) R.color.pdf_format_excel_dark else R.color.pdf_format_excel_light
        ToolFormat.POWERPOINT ->
            if (dark) R.color.pdf_format_powerpoint_dark else R.color.pdf_format_powerpoint_light
        ToolFormat.IMAGE -> if (dark) R.color.pdf_format_image_dark else R.color.pdf_format_image_light
    }
    return colorResource(res)
}
